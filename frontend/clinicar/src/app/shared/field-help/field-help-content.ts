export function obterAjudaCampo(titulo: string, contexto = ''): string | null {
  const chave = normalizarRotulo(titulo);
  const contextoNormalizado = normalizarRotulo(contexto);
  if (chave === 'veiculo' && contextoNormalizado.includes('historico-veicular')) return 'Veículo cujos agendamentos e atendimentos serão consultados.';
  if (chave.startsWith('buscar') || chave.startsWith('pesquisar')) return 'Termo usado para localizar registros na lista. A busca não altera os dados cadastrados.';
  if (chave === 'nome') {
    if (/usuario|cadastra-cliente|primeiro-acesso/.test(contextoNormalizado)) return 'Nome completo da pessoa, conforme seu documento de identificação.';
    if (contextoNormalizado.includes('servico')) return 'Nome da atividade oferecida pela oficina. Exemplo: alinhamento.';
    if (contextoNormalizado.includes('local')) return 'Nome que identifica o depósito ou área de armazenamento da oficina.';
    return 'Nome comercial da peça ou do produto. Exemplo: filtro de óleo.';
  }
  if (chave === 'fabricante') return contextoNormalizado.includes('veiculo') ? 'Marca do fabricante do veículo. Exemplo: Toyota.' : 'Marca ou empresa que fabrica a peça ou o produto.';
  if (chave === 'valor unitario') return contextoNormalizado.includes('fornecimento') ? 'Preço pago pela oficina ao fornecedor por uma unidade da peça.' : 'Valor de uma unidade da peça nesta movimentação de estoque.';
  if (chave === 'tipo' && contextoNormalizado.includes('peca')) return 'Categoria da peça ou do insumo. Selecione Óleo de motor para preencher suas características técnicas.';
  if (chave === 'tipo') return 'Modalidade usada para classificar este registro.';
  if (chave.startsWith('status')) return contextoNormalizado.includes('atendimento') || contextoNormalizado.includes('agendamento') ? 'Etapa em que se encontra o atendimento ou agendamento.' : 'Disponibilidade do registro: ativo permite seu uso; inativo mantém o cadastro sem disponibilizá-lo para novas operações.';
  if (chave.startsWith('quantidade') && (chave.includes('entrada') || chave.includes('saida'))) return 'Número de unidades que serão adicionadas ou retiradas do estoque nesta movimentação.';
  if (chave.startsWith('ajuste de')) return 'Indica se a correção vai aumentar ou reduzir o saldo físico do estoque.';
  if (chave === 'justificativa' && contextoNormalizado.includes('encerramentoalerta')) return 'Explique por que o alerta será encerrado sem normalizar o estoque. A justificativa e o responsável ficam registrados no histórico.';
  return mensagens[chave] ?? null;
}
