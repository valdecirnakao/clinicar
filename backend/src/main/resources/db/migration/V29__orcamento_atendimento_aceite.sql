CREATE TABLE atendimento_orcamento (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    id_atendimento BIGINT UNSIGNED NOT NULL,
    versao INT NOT NULL,
    status VARCHAR(20) NOT NULL,
    codigo_atendimento VARCHAR(40) NOT NULL,
    placa VARCHAR(20) NOT NULL,
    servico VARCHAR(255) NOT NULL,
    diagnostico TEXT NOT NULL,
    itens TEXT NOT NULL,
    valor_mao_obra DECIMAL(10,2) NOT NULL,
    valor_pecas DECIMAL(10,2) NOT NULL,
    valor_terceiros DECIMAL(10,2) NOT NULL,
    desconto DECIMAL(10,2) NOT NULL,
    valor_total DECIMAL(10,2) NOT NULL,
    prazo_estimado_entrega DATETIME(6) NULL,
    assinatura_conteudo VARCHAR(64) NOT NULL,
    criado_em DATETIME(6) NOT NULL,
    decidido_em DATETIME(6) NULL,
    id_decisor BIGINT UNSIGNED NULL,
    CONSTRAINT fk_orcamento_atendimento FOREIGN KEY (id_atendimento) REFERENCES atendimento(id),
    CONSTRAINT fk_orcamento_decisor FOREIGN KEY (id_decisor) REFERENCES usuario(id),
    CONSTRAINT uk_orcamento_atendimento_versao UNIQUE (id_atendimento, versao),
    INDEX idx_orcamento_atendimento_status (id_atendimento, status)
);
