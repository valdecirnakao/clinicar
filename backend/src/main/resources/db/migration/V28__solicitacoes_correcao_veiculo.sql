CREATE TABLE solicitacao_correcao_veiculo (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  veiculo_id BIGINT UNSIGNED NOT NULL,
  cliente_id BIGINT UNSIGNED NOT NULL,
  pendencia_veiculo_id BIGINT UNSIGNED NULL,
  placa_anterior VARCHAR(10) NOT NULL,
  fabricante_anterior VARCHAR(255) NOT NULL,
  modelo_anterior VARCHAR(255) NOT NULL,
  ano_modelo_combustivel_anterior VARCHAR(255) NOT NULL,
  placa_solicitada VARCHAR(10) NOT NULL,
  fabricante_solicitado VARCHAR(255) NOT NULL,
  modelo_solicitado VARCHAR(255) NOT NULL,
  ano_modelo_combustivel_solicitado VARCHAR(255) NOT NULL,
  justificativa VARCHAR(1000) NOT NULL,
  status VARCHAR(20) NOT NULL,
  solicitado_em TIMESTAMP(6) NOT NULL,
  administrador_id BIGINT UNSIGNED NULL,
  motivo_decisao VARCHAR(1000) NULL,
  decidido_em TIMESTAMP(6) NULL,
  CONSTRAINT fk_correcao_veiculo FOREIGN KEY (veiculo_id) REFERENCES veiculo(id) ON DELETE RESTRICT,
  CONSTRAINT fk_correcao_cliente FOREIGN KEY (cliente_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  CONSTRAINT fk_correcao_administrador FOREIGN KEY (administrador_id) REFERENCES usuario(id) ON DELETE RESTRICT,
  UNIQUE KEY uk_correcao_veiculo_pendente (pendencia_veiculo_id),
  INDEX idx_correcao_veiculo_status_data (status, solicitado_em),
  INDEX idx_correcao_veiculo_cliente_data (cliente_id, solicitado_em)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
